/**
 * Build the browser half into one module-loader artifact.
 *
 * The Host serves only the final `client.js`; React and the JSX runtime stay in
 * the Harness browser module table as externals.
 */
import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const entry = join(root, 'src', 'plugin.jsx')
const bodyFile = join(root, '.build', 'client-body.js')
const output = join(root, 'client.js')
const packageName = '@local/pdf-math-reader'

await build({
  entryPoints: [entry],
  outfile: bodyFile,
  bundle: true,
  format: 'iife',
  globalName: 'PdfMathReaderPlugin',
  platform: 'browser',
  target: ['chrome120', 'edge120', 'firefox120', 'safari17'],
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime'],
  logLevel: 'warning',
  legalComments: 'none',
})

const body = await readFile(bodyFile, 'utf8')
const artifact = `/* @local/pdf-math-reader — generated by scripts/build.mjs; edit src/ instead. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageName)},
  factory(require) {
    const plugin = (function (require) {
${body}
      return PdfMathReaderPlugin;
    })(require);
    return plugin;
  },
});
`

await writeFile(output, artifact)
console.log(`wrote ${output} (${Buffer.byteLength(artifact)} bytes)`)
